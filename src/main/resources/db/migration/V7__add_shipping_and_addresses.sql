-- 1. Create User Addresses Table
CREATE TABLE user_addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    address_line1 VARCHAR(255) NOT NULL,
    address_line2 VARCHAR(255),
    city VARCHAR(100) NOT NULL,
    state VARCHAR(100) NOT NULL,
    postal_code VARCHAR(20) NOT NULL,
    country VARCHAR(100) NOT NULL,
    phone_number VARCHAR(20),
    address_type VARCHAR(20) NOT NULL, -- SHIPPING or BILLING
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP,
    CONSTRAINT fk_user_address_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

-- 2. Add Address and Shipping fields to Orders Table
ALTER TABLE orders ADD COLUMN shipping_address_id BIGINT;
ALTER TABLE orders ADD COLUMN billing_address_id BIGINT;
ALTER TABLE orders ADD COLUMN shipping_cost NUMERIC(10, 2) DEFAULT 0.00;

-- Add foreign keys for referential integrity
ALTER TABLE orders ADD CONSTRAINT fk_order_shipping_address FOREIGN KEY (shipping_address_id) REFERENCES user_addresses(id);
ALTER TABLE orders ADD CONSTRAINT fk_order_billing_address FOREIGN KEY (billing_address_id) REFERENCES user_addresses(id);
