-- 1. Users Table
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    enabled BOOLEAN NOT NULL,
    created_at TIMESTAMP
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role VARCHAR(255)
);

-- 2. Custom Revision Entity (for Hibernate Envers)
-- ✅ FIX: Explicitly create the sequence that Hibernate 6 expects
CREATE SEQUENCE custom_revision_entity_seq START WITH 1 INCREMENT BY 50;

CREATE TABLE custom_revision_entity (
    id INTEGER PRIMARY KEY,
    timestamp BIGINT NOT NULL,
    username VARCHAR(255)
);

-- 3. Products Table
CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    description VARCHAR(1000),
    category VARCHAR(255),
    price NUMERIC(10, 2) NOT NULL,
    stock_quantity INTEGER NOT NULL,
    image_url VARCHAR(255)
);

-- 4. Products Audit Table (Envers)
CREATE TABLE products_aud (
    id BIGINT NOT NULL,
    rev INTEGER NOT NULL,
    revtype TINYINT, 
    name VARCHAR(255),
    description VARCHAR(1000),
    category VARCHAR(255),
    price NUMERIC(10, 2),
    stock_quantity INTEGER,
    image_url VARCHAR(255),
    PRIMARY KEY (id, rev)
);

-- 5. Product Variants Table
CREATE TABLE product_variants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    sku VARCHAR(255) NOT NULL UNIQUE,
    size VARCHAR(255) NOT NULL,
    color VARCHAR(255) NOT NULL,
    material VARCHAR(255),
    stock_quantity INTEGER NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    image_url VARCHAR(255),
    active BOOLEAN NOT NULL,
    CONSTRAINT uk_product_sku UNIQUE (product_id, sku)
);

-- 6. Carts Table
CREATE TABLE carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE
);

-- 7. Cart Items Table
CREATE TABLE cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    variant_id BIGINT,
    quantity INTEGER NOT NULL,
    price NUMERIC(10, 2) NOT NULL
);

-- 8. Orders Table
CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(255) NOT NULL,
    customer_email VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    total_price NUMERIC(10, 2) NOT NULL,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMP
);

-- 9. Order Items Table
CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    variant_id BIGINT,
    quantity INTEGER NOT NULL,
    price_at_purchase NUMERIC(10, 2) NOT NULL
);

-- 10. Reviews Table
CREATE TABLE reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    rating INTEGER NOT NULL,
    comment VARCHAR(1000),
    created_at TIMESTAMP,
    CONSTRAINT uk_product_user UNIQUE (product_id, user_id)
);

-- 11. Wishlists Table
CREATE TABLE wishlists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    added_at TIMESTAMP,
    CONSTRAINT uk_wishlist_user_product UNIQUE (user_id, product_id)
);
